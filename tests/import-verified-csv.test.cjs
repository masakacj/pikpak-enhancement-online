const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/pikpak_csv_delete_extension.js','utf8');
const ctx={};
vm.createContext(ctx);
vm.runInContext(source,ctx);
const H='A'.repeat(40);
const headers=['cloud_path','filename','size_bytes','file_id','parent_id','mime_type','cloud_hash','modified_time','verification_status','local_gcid','local_path','verified_at'];
const mk=(values)=>[headers.join(','),values.map(x=>'"'+String(x).replaceAll('"','""')+'"').join(',')].join('\r\n');
const data=['主页/视频/测,试.mp4','测,试.mp4','123','VNwEJ0J7kjv6OZE4NFoQbzcgo1','VNwEJ0J7kjv6OZE4NFoQbzcZo1','video/mp4',H,'','GCID_VERIFIED',H,'C:\\folder\\测,试.mp4','2026-10-19T14:05:00+08:00'];
const good='\uFEFF'+mk(data);
const result=ctx.parsePikPakVerifiedDeletionCsv(good);
assert.equal(result.length,1);
assert.equal(result[0].filename,'测,试.mp4');
assert.equal(result[0].local_path,'C:\\folder\\测,试.mp4');
assert.equal(result[0].cloud_hash,H);
assert(ctx.matchesVerifiedCsvLiveFile(result[0],{id:data[3],parent_id:data[4],kind:'drive#file',name:data[1],size:'123',hash:H}));
assert(!ctx.matchesVerifiedCsvLiveFile(result[0],{id:data[3],parent_id:data[4],name:data[1],size:'122',hash:H}));
assert(!ctx.matchesVerifiedCsvLiveFile(result[0],{id:data[3],parent_id:data[4],name:data[1],size:'123',hash:'B'.repeat(40)}));
assert(!ctx.matchesVerifiedCsvLiveFile(result[0],{id:data[3],parent_id:'different',name:data[1],size:'123',hash:H}));
assert.throws(()=>ctx.parsePikPakVerifiedDeletionCsv(mk(data.map((v,i)=>i===8?'NOT_VERIFIED':v))),/未验证/);
assert.throws(()=>ctx.parsePikPakVerifiedDeletionCsv(mk(data.map((v,i)=>i===9?'B'.repeat(40):v))),/未验证/);
assert.throws(()=>ctx.parsePikPakVerifiedDeletionCsv(mk(data.map((v,i)=>i===2?'120':v))+'\r\n'+data.map(x=>'"'+x+'"').join(',')),/重复云端 file_id/);
assert.throws(()=>ctx.parsePikPakVerifiedDeletionCsv('cloud_path,filename\nabc,def'),/验证列/);
assert(!source.includes('files:batchDelete'),'CSV importer must never permanently delete');
assert(source.includes('files:batchTrash'),'CSV importer sends only to trash');
assert(source.includes('await apiGet(row.file_id)'),'live cloud metadata is checked prior to action');
assert(source.includes('await confirmVerifiedCsvFileMissing(row)'),'file disappearance requires parent listing recheck');
const missing=(status,message,code)=>({status,message,code});
assert(ctx.isVerifiedCsvFileMissingError(missing(404,'文件或文件夹不存在','not_found')));
assert(ctx.isVerifiedCsvFileMissingError(missing(400,'文件或文件夹不存在','')));
assert(ctx.isVerifiedCsvFileMissingError(missing(400,'File or folder not found','')));
assert(!ctx.isVerifiedCsvFileMissingError(missing(403,'文件或文件夹不存在','not_found')));
assert(!ctx.isVerifiedCsvFileMissingError(missing(500,'文件不存在','')));
assert(!ctx.isVerifiedCsvFileMissingError(missing(429,'not found','')));
assert(!ctx.isVerifiedCsvFileMissingError(missing(0,'Failed to fetch','')));
assert(!ctx.isVerifiedCsvFileMissingError({...missing(404,'文件不存在',''),authRecoveryExhausted:true}));
(async()=>{
  let readParent='';
  ctx.apiList=async(parent)=>{readParent=parent;return [{id:'other'}];};
  await ctx.confirmVerifiedCsvFileMissing(result[0]);
  assert.equal(readParent,data[4]);
  ctx.apiList=async()=>[{id:data[3]}];
  await assert.rejects(()=>ctx.confirmVerifiedCsvFileMissing(result[0]),/仍存在/);
  ctx.apiList=async()=>{throw new Error('authorization failed');};
  await assert.rejects(()=>ctx.confirmVerifiedCsvFileMissing(result[0]),/authorization failed/);
  await assert.rejects(()=>ctx.confirmVerifiedCsvFileMissing({...result[0],parent_id:''}),/缺少父目录/);
  console.log('PASS verified CSV import/metadata/trash safety + missing-file recheck tests');
})().catch(e=>{console.error(e);process.exitCode=1;});
